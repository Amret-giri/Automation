function makeTemplate(name, format, group, updated, codeSet = "core") {
  return {
    name,
    format,
    extension: format === "Excel" ? "xlsx" : "docx",
    filename: `${name}.${format === "Excel" ? "xlsx" : "docx"}`,
    group,
    updated,
    source: "Automation Settings / Document templates",
    codes: [...new Set([...(templateCodeSets.core || []), ...(templateCodeSets[codeSet] || [])])],
  };
}

